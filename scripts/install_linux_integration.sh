#!/usr/bin/env bash
# =============================================================================
# OpenBGR - Linux desktop integration (per-user, no root required)
# =============================================================================
# Installs:
#   1. ~/.local/share/applications/openbgr.desktop
#      -> OpenBGR appears in "Open With" for image files (opens into a tab)
#   2. ~/.local/share/kio/servicemenus/openbgr.desktop   (KDE Dolphin)
#      -> right-click image → "Remove background with OpenBGR" (headless)
#   3. ~/.local/share/nautilus/scripts/Remove Background with OpenBGR (GNOME)
#      -> right-click image → Scripts → "Remove Background with OpenBGR"
#
# Usage:  ./scripts/install_linux_integration.sh [--remove]
# =============================================================================
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CTX="$ROOT/scripts/context_process.sh"

APPS_DIR="$HOME/.local/share/applications"
KDE_DIR="$HOME/.local/share/kio/servicemenus"
NAUTILUS_DIR="$HOME/.local/share/nautilus/scripts"

DESKTOP_FILE="$APPS_DIR/openbgr.desktop"
KDE_FILE="$KDE_DIR/openbgr-removebg.desktop"
NAUTILUS_FILE="$NAUTILUS_DIR/Remove Background with OpenBGR"

if [ "${1:-}" = "--remove" ] || [ "${1:-}" = "--uninstall" ]; then
  rm -f "$DESKTOP_FILE" "$KDE_FILE" "$NAUTILUS_FILE"
  update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
  echo "[Done] OpenBGR desktop integration removed."
  exit 0
fi

mkdir -p "$APPS_DIR" "$KDE_DIR" "$NAUTILUS_DIR"

cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=OpenBGR
Comment=Local AI Background Removal Studio
Exec="$ROOT/start.sh" %F
MimeType=image/png;image/jpeg;image/webp;image/bmp;image/tiff;image/gif;
Terminal=false
Categories=Graphics;Photography;
EOF

cat > "$KDE_FILE" <<EOF
[Desktop Entry]
Type=Service
Actions=openbgrRemoveBG;
MimeType=image/png;image/jpeg;image/webp;image/bmp;image/tiff;image/gif;
X-KDE-ServiceTypes=KonqPopupMenu/Plugin
X-KDE-Priority=TopLevel

[Desktop Action openbgrRemoveBG]
Name=Remove background with OpenBGR
Exec="$CTX" %F
EOF

cat > "$NAUTILUS_FILE" <<EOF
#!/usr/bin/env bash
# Generated by install_linux_integration.sh; delegates to context_process.sh.
while IFS= read -r f; do
  [ -n "\$f" ] && set -- "\$@" "\$f"
done <<'LIST'
\$NAUTILUS_SCRIPT_SELECTED_FILE_PATHS
LIST
exec "$CTX" "\$@"
EOF
chmod +x "$NAUTILUS_FILE" "$CTX" "$ROOT/start.sh" 2>/dev/null || true

update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
kbuildsycoca6 >/dev/null 2>&1 || kbuildsycoca5 >/dev/null 2>&1 || true

echo "[Done] Installed:"
echo "       - 'Open With → OpenBGR' for image files (all desktops)"
echo "       - KDE Dolphin: right-click → 'Remove background with OpenBGR'"
echo "       - GNOME Files: right-click → Scripts → 'Remove Background with OpenBGR'"
