export const dom = new Proxy(
  {},
  {
    get(target, prop) {
      if (typeof prop !== "string") return undefined;
      if (Object.prototype.hasOwnProperty.call(target, prop)) {
        return target[prop];
      }
      return globalThis.document?.getElementById?.(prop) ?? null;
    },
    set(target, prop, value) {
      target[prop] = value;
      return true;
    },
  }
);
